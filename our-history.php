<!-- Scroll Animation Pop Up Script -->
<script>
    document.addEventListener("DOMContentLoaded", function() {
        const popElements = document.querySelectorAll("[data-scroll-pop]");
        
        const observerOptions = {
            root: null,
            rootMargin: "0px 0px -40px 0px",
            threshold: 0.1
        };

        const scrollObserver = new IntersectionObserver(function(entries) {
            entries.forEach(function(entry) {
                if (entry.isIntersecting) {
                    entry.target.classList.add("scroll-in-view");
                } else {
                    entry.target.classList.remove("scroll-in-view");
                }
            });
        }, observerOptions);

        popElements.forEach(function(el) {
            scrollObserver.observe(el);
        });

        // Smooth scroll from top image to snake timeline
        const imgLink = document.querySelector('.history-image-box-link');
        if (imgLink) {
            imgLink.addEventListener('click', function(e) {
                e.preventDefault();
                const target = document.getElementById('tacit-snake-timeline');
                if (target) {
                    target.scrollIntoView({ behavior: 'smooth', block: 'start' });
                }
            });
        }
    });
</script>
